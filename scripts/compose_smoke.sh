#!/usr/bin/env bash
# Compose smoke test — the acceptance gate for the one-command demo.
#
#   ./scripts/compose_smoke.sh
#
# Brings the stack up, waits for health, drives the real MCP endpoint
# over Streamable HTTP as the seeded demo agent, asserts one ALLOW
# (demo.read) and one DENY (demo.write, pinned default-deny), probes
# kev reachability from the gateway container (non-fatal), then tears
# everything down (`docker compose down -v`). Exits non-zero on any
# failed assertion.
#
# MUST run on a docker host — docker is not installed on the repo's
# build VM, so this script was validated statically only (see
# docs/build-log-fragment-ws1.md).
set -euo pipefail

cd "$(dirname "$0")/.."
command -v docker >/dev/null 2>&1 || { echo "FATAL: docker not found" >&2; exit 1; }
command -v python3 >/dev/null 2>&1 || { echo "FATAL: python3 not found (needed for the JSON-RPC assertions)" >&2; exit 1; }
command -v curl >/dev/null 2>&1 || { echo "FATAL: curl not found" >&2; exit 1; }

pass() { echo "PASS: $1"; }
fail() { echo "FAIL: $1" >&2; exit 1; }
warn() { echo "WARN: $1" >&2; }

echo "== docker compose up --build =="
docker compose up -d --build
trap 'echo "== docker compose down -v =="; docker compose down -v' EXIT

echo "== waiting for gateway /healthz =="
healthy=0
for i in $(seq 1 60); do
    if curl -sf http://127.0.0.1:8000/healthz >/dev/null 2>&1; then
        healthy=1
        break
    fi
    sleep 2
done
[ "$healthy" = "1" ] || fail "gateway never became healthy (60 x 2s)"
pass "gateway healthy"

echo "== reading demo credentials =="
# The seed wrote these (0600) on first boot; the raw secret is shown
# once here and never persisted elsewhere.
creds="$(docker compose exec -T gateway cat /data/demo-credentials.env)" \
    || fail "could not read /data/demo-credentials.env (was the seed run?)"
# The file holds KEY='value' lines generated by the seed; eval is safe here
# (values are shlex.quote'd by the seed; secrets are token_urlsafe).
eval "$creds"
[ -n "${DEMO_AGENT_ID:-}" ] && [ -n "${DEMO_CLIENT_ID:-}" ] && [ -n "${DEMO_CLIENT_SECRET:-}" ] \
    || fail "demo credentials incomplete"
pass "demo credentials loaded (agent '${DEMO_AGENT_ID}')"

export SMOKE_AUTH="Basic $(printf '%s:%s' "$DEMO_CLIENT_ID" "$DEMO_CLIENT_SECRET" | base64 | tr -d '\n')"

echo "== MCP handshake + tools/list =="
python3 - <<'EOF'
import json, os, sys, urllib.request

BASE = "http://127.0.0.1:8000/mcp"
AUTH = os.environ["SMOKE_AUTH"]
RID = 0
SESSION = [None]

def rpc(method, params=None, rpc_id=None, notification=False):
    global RID
    if rpc_id is None:
        RID += 1
        rpc_id = RID
    body = {"jsonrpc": "2.0", "method": method}
    if not notification:
        body["id"] = rpc_id
    if params is not None:
        body["params"] = params
    headers = {
        "Content-Type": "application/json",
        "Accept": "application/json, text/event-stream",
        "Authorization": AUTH,
        "MCP-Protocol-Version": "2025-06-18",
    }
    if SESSION[0]:
        headers["Mcp-Session-Id"] = SESSION[0]
    req = urllib.request.Request(BASE, data=json.dumps(body).encode(), headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            if SESSION[0] is None:
                SESSION[0] = r.headers.get("mcp-session-id")
            raw = r.read().decode()
    except urllib.error.HTTPError as e:
        sys.exit(f"FAIL: {method} -> HTTP {e.code}: {e.read().decode()[:300]}")
    if notification or not raw.strip():
        return None
    # Streamable HTTP may answer as SSE; unwrap data: lines.
    texts = [ln[5:].strip() for ln in raw.splitlines() if ln.startswith("data:")]
    payload = texts[-1] if texts else raw
    return json.loads(payload)

init = rpc("initialize", {"protocolVersion": "2025-06-18", "capabilities": {},
                          "clientInfo": {"name": "compose-smoke", "version": "1"}})
assert isinstance(init, dict) and "result" in init, f"initialize failed: {init}"
print("PASS: MCP initialize handshake")
rpc("notifications/initialized", {}, notification=True)

listed = rpc("tools/list")
names = [t["name"] for t in listed["result"]["tools"]]
assert "demo.read" in names and "demo.write" in names, f"demo tools not listed: {names}"
print(f"PASS: tools/list exposes demo.read + demo.write ({len(names)} tools total)")

# --- ALLOW: demo.read has an explicit seeded allow rule ----------------
res = rpc("tools/call", {"name": "demo.read", "arguments": {"q": "smoke"}})
call = res.get("result", {})
assert call.get("isError") is not True, f"demo.read errored: {call}"
text = call["content"][0]["text"]
assert "read-ok" in text, f"demo.read unexpected payload: {text[:200]}"
print("PASS: demo.read -> ALLOW (policy allow rule matched)")

# --- DENY: demo.write has no allow rule -> pinned default-deny ---------
res = rpc("tools/call", {"name": "demo.write", "arguments": {}})
call = res.get("result", {})
assert call.get("isError") is True, f"demo.write was not an error: {call}"
text = call["content"][0]["text"]
assert "policy_denied" in text, f"demo.write wrong error: {text[:200]}"
print("PASS: demo.write -> DENY (policy_denied, pinned default-deny)")

print("SMOKE_OK")
EOF

echo "== kev reachability from the gateway container (non-fatal) =="
if docker compose exec -T gateway python3 -c \
    "import urllib.request; urllib.request.urlopen('http://kev:8009/docs', timeout=10)" \
    >/dev/null 2>&1; then
    pass "kev reachable at http://kev:8009 (model loaded)"
else
    warn "kev not reachable at http://kev:8009 (judge stays disabled; gateway unaffected)"
fi

echo "ALL SMOKE CHECKS PASSED"
